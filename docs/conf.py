def autodoc_skip_pydantic(
    app: Sphinx,
    what: Literal[
        "module",
        "class",
        "exception",
        "function",
        "decorator",
        "method",
        "property",
        "attribute",
        "data",
        "type",
    ],
    name: str,
    obj: object,
    skip: bool,
    options: dict[str, str],
) -> bool | None:
    """Skip class-body fields represented by the ``INSTANCE_ATTR`` sentinel."""
    del app, skip, options

    if what == "class" and obj == INSTANCE_ATTR:
        return True

    if name == "model_config":
        return True

    return None


