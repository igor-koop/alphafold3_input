def module_type_aliases(
    app: Sphinx,
    env: BuildEnvironment,
) -> None:
    """Build local package aliases for Python references."""
    del app

    domain: PythonDomain = env.domains["py"]
    objects: dict[str, ObjectEntry] = domain.objects

    aliases: dict[str, str] = {}

    for name, entry in objects.items():
        match name.split("."):
            case [module, _submodule, alias] if module == __module_name__:
                pass
            case _:
                continue

        if entry.objtype not in {"class", "exception"}:
            continue

        if alias in aliases and aliases[alias] != name:
            msg: str = (
                f"Conflicting alias '{alias}' for '{name}' and "
                f"'{aliases[alias]}' in intersphinx inventory."
            )
            raise ValueError(msg)

        aliases[alias] = name

    setattr(env, "module_type_aliases", aliases)


def resolve_builtins_reference(
    app: Sphinx,
    env: BuildEnvironment,
    node: pending_xref,
    contnode: TextElement,
) -> Node | None:
    """Resolve ``None``, ``True``, and ``False`` references."""
    del app, env

    if node.get("refdomain") != "py":
        return None

    target: Any = node.get("reftarget")
    if not isinstance(target, str) or target == "":
        return None

    if target in ("None", "True", "False"):
        return nodes.reference(
            "",
            "",
            contnode,
            internal=False,
            refuri=f"https://docs.python.org/3/library/constants.html#{target}",
        )

    return None


def resolve_self_reference(
    app: Sphinx,
    env: BuildEnvironment,
    node: pending_xref,
    contnode: TextElement,
) -> Node | None:
    """Resolve ``Self`` references against the current class context."""
    if node.get("refdomain") != "py":
        return None

    target: Any = node.get("reftarget")
    if not isinstance(target, str) or target == "":
        return None

    domain: PythonDomain = env.domains["py"]
    objects: dict[str, ObjectEntry] = domain.objects

    content: TextElement = contnode.deepcopy()

    if target == "Self":
        module: str | None = node.get("py:module")
        element: str | None = node.get("py:class")

        if module is None or element is None:
            return None

        candidate = f"{module}.{element}"

        if candidate in objects:
            for child in content.children:
                if isinstance(child, nodes.Text) and child == "Self":
                    child.parent.replace(child, nodes.Text(element))

            return make_refnode(
                app.builder,
                node.get("refdoc", env.docname),
                objects[candidate].docname,
                objects[candidate].node_id,
                [content],
                candidate,
            )

    return None


def resolve_local_reference(
    app: Sphinx,
    env: BuildEnvironment,
    node: pending_xref,
    contnode: TextElement,
) -> Node | None:
    """Resolve local package references using cached aliases."""
    if node.get("refdomain") != "py":
        return None

    target: Any = node.get("reftarget")
    if not isinstance(target, str) or target == "":
        return None

    domain: PythonDomain = env.domains["py"]
    objects: dict[str, ObjectEntry] = domain.objects

    if aliases := getattr(env, "module_type_aliases", None):
        for alias, candidate in aliases.items():
            if alias in target and candidate in objects:
                return domain.resolve_xref(
                    env=env,
                    fromdocname=node.get("refdoc", env.docname),
                    builder=app.builder,
                    type=node["reftype"],
                    target=target.replace(alias, candidate),
                    node=node,
                    contnode=contnode,
                )

    return None


def resolve_global_reference(  # noqa: C901
    app: Sphinx,
    env: BuildEnvironment,
    node: pending_xref,
    contnode: TextElement,
) -> Node | None:
    """Resolve configured global aliases via intersphinx.

    If the fully qualified target cannot be resolved directly, fall back to the
    longest documented Python-object prefix and synthesize a URL by replacing
    the fragment with the full candidate target.
    """
    if node.get("refdomain") != "py":
        return None

    target: Any = node.get("reftarget")
    if not isinstance(target, str) or target == "":
        return None

    config: Config = getattr(env, "config", Config())
    reference: pending_xref = node.deepcopy()
    content: TextElement = contnode.deepcopy()

    candidate: str | None = None
    if aliases := getattr(config, "napoleon_type_aliases", None):
        for alias, _candidate in aliases.items():
            if alias in target:
                candidate: str | None = _candidate.lstrip("~")
                break

    if not candidate:
        return None

    reference["reftarget"] = target.replace(alias, candidate)

    if resolved := missing_reference(app, env, reference, content):
        return resolved

    inventories = InventoryAdapter(env)

    while candidate:
        candidate, _, _ = candidate.rpartition(".")

        for role in inventories.main_inventory.values():
            item: InventoryItem | None = role.get(candidate)

            if item is not None:
                base, _, _ = item.uri.partition("#")
                return nodes.reference(
                    "",
                    "",
                    content,
                    internal=False,
                    refuri=f"{base}#{reference['reftarget']}",
                )

    return None


