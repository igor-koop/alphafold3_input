def setup(app: Sphinx) -> None:
    """Register custom Sphinx hooks and Napoleon patches."""
    python_return_field()
    python_yield_field()

    setattr(
        GoogleDocstring,
        "_consume_fields",
        napoleon_fields_consumer,
    )
    setattr(
        GoogleDocstring,
        "_consume_returns_section",
        napoleon_returns_consumer,
    )

    setattr(
        GoogleDocstring,
        "_parse_attributes_section",
        napoleon_attributes_parser,
    )
    setattr(
        GoogleDocstring,
        "_parse_methods_section",
        napoleon_methods_parser,
    )
    setattr(
        GoogleDocstring,
        "_parse_yields_section",
        lambda self, section: napoleon_returns_parser(
            self,
            section=section,
            directive="yields",
        ),
    )
    setattr(
        GoogleDocstring,
        "_parse_returns_section",
        lambda self, section: napoleon_returns_parser(
            self,
            section=section,
            directive="returns",
        ),
    )

    app.connect(
        event="autodoc-skip-member",
        callback=autodoc_skip_pydantic,
        priority=500,
    )
    app.connect(
        "env-updated",
        module_type_aliases,
        priority=500,
    )

    app.connect(
        "missing-reference",
        resolve_builtins_reference,
        priority=500,
    )
    app.connect(
        "missing-reference",
        resolve_self_reference,
        priority=500,
    )
    app.connect(
        "missing-reference",
        resolve_local_reference,
        priority=500,
    )
    app.connect(
        "missing-reference",
        resolve_global_reference,
        priority=500,
    )
